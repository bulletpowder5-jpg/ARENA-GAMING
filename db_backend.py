"""PostgreSQL/Neon adapter for ARENA, with a small SQLite-compatible query layer."""
import os
import re
import sqlite3

import psycopg
from psycopg.rows import dict_row


SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT NOT NULL, email TEXT NOT NULL, password_hash TEXT NOT NULL,
 bio TEXT NOT NULL DEFAULT '', is_admin INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS posts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS likes (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id, post_id)
);
CREATE TABLE IF NOT EXISTS comments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 500),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS follows (
 follower_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 followed_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (follower_id, followed_id), CHECK (follower_id != followed_id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 actor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN ('like','comment','follow')),
 post_id INTEGER REFERENCES posts(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 is_read INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS groups (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS group_members (
 group_id INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(group_id,user_id)
);
CREATE TABLE IF NOT EXISTS group_posts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 1000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS messages (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 2000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, is_read INTEGER NOT NULL DEFAULT 0,
 CHECK(sender_id != recipient_id)
);
CREATE INDEX IF NOT EXISTS idx_messages_pair ON messages(sender_id,recipient_id,id);
CREATE INDEX IF NOT EXISTS idx_group_posts ON group_posts(group_id,id);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci ON users (LOWER(email));
CREATE UNIQUE INDEX IF NOT EXISTS groups_name_ci ON groups (LOWER(name));
"""


class CursorAdapter:
    def __init__(self, cursor, prefetched=None):
        self.cursor = cursor
        self.prefetched = prefetched
        self.lastrowid = prefetched.get("id") if prefetched and "id" in prefetched else None

    @property
    def rowcount(self):
        return self.cursor.rowcount

    def fetchone(self):
        if self.prefetched is not None:
            row, self.prefetched = self.prefetched, None
            return row
        return self.cursor.fetchone()

    def fetchall(self):
        rows = []
        if self.prefetched is not None:
            rows.append(self.prefetched)
            self.prefetched = None
        rows.extend(self.cursor.fetchall())
        return rows


class ConnectionAdapter:
    def __init__(self, url):
        if "sslmode=" not in url:
            url += ("&" if "?" in url else "?") + "sslmode=require"
        self.connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=12)

    def execute(self, sql, params=()):
        query = sql.strip()
        query = re.sub(r"([A-Za-z_][A-Za-z0-9_.]*)\s*=\s*\?\s+COLLATE\s+NOCASE",
                       r"LOWER(\1) = LOWER(?)", query, flags=re.IGNORECASE)
        query = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", query, flags=re.IGNORECASE)
        ignored = bool(re.match(r"INSERT\s+OR\s+IGNORE\s+INTO", sql.strip(), flags=re.IGNORECASE))
        # The SQLite adapter's INSERT OR IGNORE statements are idempotent in PostgreSQL too.
        if ignored:
            query += " ON CONFLICT DO NOTHING"
        needs_id = bool(re.match(r"INSERT\s+INTO\s+(users|groups)\b", query, flags=re.IGNORECASE)) and "RETURNING" not in query.upper()
        if needs_id:
            query += " RETURNING id"
        query = query.replace("?", "%s")
        try:
            cur = self.connection.execute(query, params)
            prefetched = cur.fetchone() if needs_id else None
            return CursorAdapter(cur, prefetched)
        except psycopg.IntegrityError as exc:
            self.connection.rollback()
            raise sqlite3.IntegrityError(str(exc)) from exc

    def commit(self):
        self.connection.commit()

    def close(self):
        self.connection.close()


def connect_database(url):
    return ConnectionAdapter(url)


def initialize_database(url):
    if "sslmode=" not in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"
    with psycopg.connect(url, connect_timeout=12) as conn:
        with conn.cursor() as cur:
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    cur.execute(statement)
        conn.commit()
